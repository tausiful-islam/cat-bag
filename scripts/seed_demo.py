#!/usr/bin/env python3
"""Insert demo catalog data (products, variants, images) using the
service-role key. Development helper — real content is managed in the
admin panel. Placeholder images are generated by
gen_placeholder_images.py.
"""
import json, subprocess, urllib.request, uuid, os

REF = "gfjcxmcbwumzuwwubolj"
BASE = f"https://{REF}.supabase.co"
KEYS = json.load(open("/tmp/sb_keys.json"))
SR = {k["name"]: k["api_key"] for k in KEYS}["service_role"]
IMG_DIR = "/tmp/catbag-imgs"

def api(method, path, body=None, content_type="application/json"):
    req = urllib.request.Request(
        f"{BASE}{path}",
        data=json.dumps(body).encode() if body is not None else None,
        method=method,
        headers={"apikey": SR, "Authorization": f"Bearer {SR}", "Content-Type": content_type},
    )
    with urllib.request.urlopen(req, timeout=60) as r:
        raw = r.read().decode()
        return json.loads(raw) if raw else None

def upload_image(local, storage_path):
    data = open(local, "rb").read()
    req = urllib.request.Request(
        f"{BASE}/storage/v1/object/product-images/{storage_path}",
        data=data,
        method="POST",
        headers={"apikey": SR, "Authorization": f"Bearer {SR}", "Content-Type": "image/jpeg"},
    )
    with urllib.request.urlopen(req, timeout=60) as r:
        r.read()

# slug, name, style(idx), price, sale, categories, colours(name,hex,stock), is_new, is_featured
PRODUCTS = [
    ("aria-crossbody", "Aria Crossbody", 0, 6900, None, ["crossbody-bags"],
     [("Espresso", "#3f3227", 8), ("Ivory", "#e8e1d2", 5)], True, True),
    ("nova-crossbody", "Nova Crossbody", 1, 5400, 4800, ["crossbody-bags"],
     [("Chestnut", "#6d5138", 10), ("Black", "#1a1512", 7)], True, False),
    ("lyra-shoulder-bag", "Lyra Shoulder Bag", 2, 8200, None, ["shoulder-bags"],
     [("Taupe", "#8a7a63", 6), ("Espresso", "#3f3227", 4)], True, True),
    ("vela-shoulder-bag", "Vela Shoulder Bag", 3, 7600, None, ["shoulder-bags"],
     [("Sand", "#cbb99a", 9)], False, False),
    ("odessa-tote", "Odessa Tote", 4, 9400, None, ["tote-bags"],
     [("Espresso", "#3f3227", 5), ("Ivory", "#e8e1d2", 3)], True, True),
    ("marlow-tote", "Marlow Tote", 5, 8800, 7900, ["tote-bags"],
     [("Black", "#1a1512", 6)], False, False),
    ("isla-card-holder", "Isla Card Holder", 6, 1900, None, ["accessories"],
     [("Espresso", "#3f3227", 15), ("Sand", "#cbb99a", 12)], True, False),
    ("rue-pouch", "Rue Pouch", 7, 2600, None, ["accessories"],
     [("Chestnut", "#6d5138", 11)], True, False),
]

STYLES = ["crossbody", "shoulder", "tote", "accessory"]
DIMENSIONS = {
    "crossbody": (22, 7, 15),
    "shoulder": (26, 9, 17),
    "tote": (32, 14, 26),
    "accessory": (11, 2, 8),
}
DESCRIPTIONS = {
    "crossbody": "A compact everyday crossbody with a clean silhouette, secure flap and an adjustable strap — designed to move lightly through the day.",
    "shoulder": "A softly structured shoulder bag with quiet presence. Roomy enough for the day's essentials, refined enough for the evening.",
    "tote": "A generous, elegantly proportioned tote for work and beyond. Carries the day with ease and keeps its shape beautifully.",
    "accessory": "A small, considered piece for the essentials — slipped into a larger bag or carried on its own.",
}

# fetch categories
cats = api("GET", "/rest/v1/categories?select=id,slug")
cat_map = {c["slug"]: c["id"] for c in cats}

for slug, name, idx, price, sale, cat_slugs, colours, is_new, is_featured in PRODUCTS:
    style = STYLES[idx % 4] if idx < 4 else ("tote" if idx < 6 else "accessory")
    style = ["crossbody", "crossbody", "shoulder", "shoulder", "tote", "tote", "accessory", "accessory"][idx]
    dims = DIMENSIONS[style]

    existing = api("GET", f"/rest/v1/products?select=id&slug=eq.{slug}")
    if existing:
        pid = existing[0]["id"]
        print(f"exists: {slug}")
    else:
        created = api("POST", "/rest/v1/products", {
            "slug": slug,
            "name": name,
            "description": DESCRIPTIONS[style],
            "sku": f"CB-{slug.upper()[:12]}",
            "price": price,
            "sale_price": sale,
            "dim_l_cm": dims[0],
            "dim_w_cm": dims[1],
            "dim_h_cm": dims[2],
            "is_new": is_new,
            "is_featured": is_featured,
            "status": "active",
        })
        pid = created[0]["id"] if isinstance(created, list) and created else None
        if not pid:
            pid = api("GET", f"/rest/v1/products?select=id&slug=eq.{slug}")[0]["id"]
        print(f"created: {slug} ({pid})")

    # link categories
    for cs in cat_slugs:
        api("POST", "/rest/v1/product_categories", {"product_id": pid, "category_id": cat_map[cs]})

    # variants
    for cname, chex, stock in colours:
        vsku = f"CB-{slug.upper()[:10]}-{cname.upper()[:4]}"
        already = api("GET", f"/rest/v1/product_variants?select=id&sku=eq.{vsku}")
        if not already:
            api("POST", "/rest/v1/product_variants", {
                "product_id": pid, "colour_name": cname, "colour_hex": chex,
                "sku": vsku, "stock": stock, "is_active": True,
            })
            mv = api("GET", f"/rest/v1/product_variants?select=id,stock&sku=eq.{vsku}")[0]
            api("POST", "/rest/v1/inventory_movements", {
                "product_id": pid, "variant_id": mv["id"], "delta": stock,
                "stock_after": stock, "reason": "initial",
            })

    # images
    have = api("GET", f"/rest/v1/product_images?select=id&product_id=eq.{pid}")
    if not have:
        for k in range(2):
            local = f"{IMG_DIR}/{style}-{idx}-{k}.jpg"
            if not os.path.exists(local):
                continue
            spath = f"{pid}/{k}-{uuid.uuid4().hex[:6]}.jpg"
            upload_image(local, spath)
            api("POST", "/rest/v1/product_images", {
                "product_id": pid, "storage_path": spath,
                "alt": f"{name} — {colours[0][0]}", "sort_order": k,
            })

print("demo catalog seeded")
